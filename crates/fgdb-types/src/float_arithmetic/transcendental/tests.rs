fn value(bits: u64) -> CanonicalF64 {
    CanonicalF64::from_bits_canonical(bits).expect("canonical test bits")
}

fn evaluate(kernel: Kernel, argument: CanonicalF64, x: CanonicalF64) -> Outcome {
    match kernel {
        Exp => argument.exp(),
        Ln => argument.ln(),
        Log10 => argument.log10(),
        Sin => argument.sin(),
        Cos => argument.cos(),
        Tan => argument.tan(),
        Atan => argument.atan(),
        Asin => argument.asin(),
        Acos => argument.acos(),
        Atan2 => argument.atan2(x),
    }
}

#[test]
fn known_answers_reproduce_bit_for_bit() {
    let mut failures = Vec::new();
    for &(kernel, argument, x, expected) in KNOWN {
        let got = evaluate(kernel, value(argument), value(x));
        let matches = match (expected, got) {
            (Bits(bits), Ok(result)) => result.to_bits() == bits,
            (Overflow, Err(FloatArithmeticError::Overflow)) => true,
            (Pole, Err(FloatArithmeticError::DivisionByZero)) => true,
            _ => false,
        };
        if !matches {
            failures.push(format!(
                "{kernel:?}({argument:#018x}, {x:#018x}) = {got:?}, expected {expected:?}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} known answers differ:\n{}",
        failures.len(),
        KNOWN.len(),
        failures.join("\n")
    );
    // Every kernel is exercised, and so are both refusals.
    for kernel in KERNELS {
        assert!(
            KNOWN.iter().filter(|row| row.0 == kernel).count() >= 40,
            "{kernel:?}"
        );
    }
    assert!(KNOWN.iter().any(|row| matches!(row.3, Overflow)));
    assert!(KNOWN.iter().any(|row| matches!(row.3, Pole)));
}

/// Distance in units in the last place between two finite values of one sign.
fn ulps(a: f64, b: f64) -> u64 {
    let key = |v: f64| {
        let bits = v.to_bits() as i64;
        if bits < 0 { i64::MIN - bits } else { bits }
    };
    key(a).abs_diff(key(b))
}

#[test]
fn every_result_lies_within_two_ulps_of_the_host_libm() {
    type Host = fn(f64) -> f64;
    let kernels: [(Kernel, Host, f64, f64); 9] = [
        (Exp, f64::exp, -700.0, 700.0),
        (Ln, f64::ln, 1e-300, 1e300),
        (Log10, f64::log10, 1e-300, 1e300),
        (Sin, f64::sin, -1e6, 1e6),
        (Cos, f64::cos, -1e6, 1e6),
        (Tan, f64::tan, -1e3, 1e3),
        (Atan, f64::atan, -1e10, 1e10),
        (Asin, f64::asin, -1.0, 1.0),
        (Acos, f64::acos, -1.0, 1.0),
    ];
    // A fixed xorshift sequence: the same arguments on every run.
    let mut state = 0x9E37_79B9_7F4A_7C15_u64;
    let mut next = move || {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        (state >> 11) as f64 / (1_u64 << 53) as f64
    };
    for (kernel, host, low, high) in kernels {
        for _ in 0..2048 {
            let unit = next();
            let argument = if low > 0.0 {
                // Logarithmic spread across the positive range.
                (low.ln() + unit * (high.ln() - low.ln())).exp()
            } else {
                low + unit * (high - low)
            };
            let argument = CanonicalF64::new(argument);
            let ours = evaluate(kernel, argument, argument)
                .expect("finite in-range argument")
                .get();
            let theirs = host(argument.get());
            assert!(
                ulps(ours, theirs) <= 2,
                "{kernel:?}({}) = {ours:e}, host {theirs:e}",
                argument.get()
            );
        }
    }
    for _ in 0..2048 {
        let (y, x) = (
            CanonicalF64::new(next() * 8.0 - 4.0),
            CanonicalF64::new(next() * 8.0 - 4.0),
        );
        let ours = y.atan2(x).expect("finite atan2").get();
        assert!(
            ulps(ours, y.get().atan2(x.get())) <= 2,
            "atan2({}, {})",
            y.get(),
            x.get()
        );
    }
}

#[test]
fn domains_poles_and_infinities() {
    let nan = CanonicalF64::new(f64::NAN);
    let f = CanonicalF64::new;
    let bits = |result: Outcome| result.map(|value| value.to_bits());
    for kernel in [
        CanonicalF64::exp,
        CanonicalF64::ln,
        CanonicalF64::log10,
        CanonicalF64::sin,
        CanonicalF64::cos,
        CanonicalF64::tan,
        CanonicalF64::atan,
        CanonicalF64::asin,
        CanonicalF64::acos,
    ] {
        assert_eq!(bits(kernel(nan)), Ok(nan.to_bits()), "NaN in is NaN out");
    }
    assert_eq!(bits(nan.atan2(f(1.0))), Ok(nan.to_bits()));
    // Outside the real domain: NaN, as sqrt's.
    for outside in [
        f(-1.0).ln(),
        f(-1e-300).log10(),
        f(1.5).asin(),
        f(-1.0000000000000002).acos(),
    ] {
        assert_eq!(bits(outside), Ok(nan.to_bits()));
    }
    // Poles and overflow refuse as the arithmetic kernel's do.
    assert_eq!(f(0.0).ln(), Err(FloatArithmeticError::DivisionByZero));
    assert_eq!(f(0.0).log10(), Err(FloatArithmeticError::DivisionByZero));
    assert_eq!(f(710.0).exp(), Err(FloatArithmeticError::Overflow));
    assert!(f(709.0).exp().is_ok());
    // Infinite arguments follow IEEE 754.
    assert_eq!(bits(f(f64::NEG_INFINITY).exp()), Ok(0));
    assert_eq!(bits(f(f64::INFINITY).exp()), Ok(f64::INFINITY.to_bits()));
    assert_eq!(bits(f(f64::INFINITY).ln()), Ok(f64::INFINITY.to_bits()));
    assert_eq!(bits(f(f64::INFINITY).sin()), Ok(nan.to_bits()));
    assert_eq!(bits(f(f64::NEG_INFINITY).cos()), Ok(nan.to_bits()));
    assert_eq!(bits(f(f64::INFINITY).atan()), Ok(PI_O_2));
    assert_eq!(bits(f(-1000.0).exp()), Ok(0), "underflow is zero");
    // atan2 on the axes, with no negative zero.
    assert_eq!(bits(f(0.0).atan2(f(-1.0))), Ok(PI));
    assert_eq!(bits(f(0.0).atan2(f(0.0))), Ok(0));
    assert_eq!(bits(f(1.0).atan2(f(0.0))), Ok(PI_O_2));
    assert_eq!(
        bits(f(f64::INFINITY).atan2(f(f64::NEG_INFINITY))),
        Ok((3.0 * f64::from_bits(PIO4)).to_bits())
    );
}

struct Sweep(u64);
impl Sweep {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }
    /// A finite argument from bits alone: a biased exponent in [low, high],
    /// any fraction, and a random sign when `signed`.
    fn argument(&mut self, low: u64, high: u64, signed: bool) -> CanonicalF64 {
        let exponent = low + (self.next() >> 52) % (high - low + 1);
        let fraction = self.next() & ((1 << 52) - 1);
        let sign = if signed { (self.next() & 1) << 63 } else { 0 };
        let bits = sign | (exponent << 52) | fraction;
        value(if bits == 1 << 63 { 0 } else { bits })
    }
}

/// FNV-1a over result words; a refusal folds as a NaN payload of its own.
fn fold(digest: u64, result: Outcome) -> u64 {
    let word = match result {
        Ok(value) => value.to_bits(),
        Err(FloatArithmeticError::Overflow) => 0xFFF0_0000_0000_0001,
        Err(FloatArithmeticError::DivisionByZero) => 0xFFF0_0000_0000_0002,
        Err(FloatArithmeticError::NonFinite) => 0xFFF0_0000_0000_0003,
    };
    (digest ^ word).wrapping_mul(0x0000_0100_0000_01B3)
}

const FNV_OFFSET: u64 = 0xCBF2_9CE4_8422_2325;
const SWEEP_LENGTH: usize = 12_000;

/// Each kernel over 12,000 seeded arguments spanning its whole domain, the
/// results folded into one digest per kernel. The digests come from the same
/// independent implementation as KNOWN: any changed bit in any of these
/// 120,000 results changes a digest. Exponent ranges reach the subnormal,
/// overflow and huge-reduction branches.
#[test]
fn seeded_sweeps_reproduce_their_digests() {
    let unary: [(Kernel, u64, u64, bool, u64); 9] = [
        (Exp, 0x3c0, 0x408, true, 0xc183dfa8a155689c),
        (Ln, 0x000, 0x7fe, false, 0x6fc713bee0fcfa0e),
        (Log10, 0x000, 0x7fe, false, 0x3ca25b953c214d9b),
        (Sin, 0x3c0, 0x7fe, true, 0x0ea03e578c6b1530),
        (Cos, 0x3c0, 0x7fe, true, 0xd086784ba755dcdd),
        (Tan, 0x3c0, 0x7fe, true, 0xc6d3381c6cbf3bb1),
        (Atan, 0x300, 0x7fe, true, 0xaabd5ed1eb15c732),
        (Asin, 0x3c0, 0x3ff, true, 0xe7e1f47deb09d966),
        (Acos, 0x3c0, 0x3ff, true, 0x93d53114904d7992),
    ];
    let mut mismatched = Vec::new();
    for (index, (kernel, low, high, signed, expected)) in unary.into_iter().enumerate() {
        let mut sweep = Sweep(0x9E37_79B9_7F4A_7C15 ^ index as u64);
        let mut digest = FNV_OFFSET;
        for _ in 0..SWEEP_LENGTH {
            let argument = sweep.argument(low, high, signed);
            digest = fold(digest, evaluate(kernel, argument, argument));
        }
        if digest != expected {
            mismatched.push(format!("{kernel:?}: {digest:#018x}"));
        }
    }
    let mut sweep = Sweep(0x9E37_79B9_7F4A_7C15 ^ 9);
    let mut digest = FNV_OFFSET;
    for _ in 0..SWEEP_LENGTH {
        let y = sweep.argument(0x3a0, 0x460, true);
        let x = sweep.argument(0x3a0, 0x460, true);
        digest = fold(digest, y.atan2(x));
    }
    if digest != 0x3283d5809e71a22e {
        mismatched.push(format!("Atan2: {digest:#018x}"));
    }
    assert!(
        mismatched.is_empty(),
        "sweep digests changed: {mismatched:?}"
    );
}

