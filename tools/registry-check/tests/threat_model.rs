#[test]
fn tm_claim_scan_rules_are_all_exercised() {
    // Every rule fires on at least one crafted overreach. A rule nobody has
    // seen fire is a rule that may be syntactically incapable of firing.
    let registry = registry();
    let probes = [
        (
            "TMS-1",
            "Data remains confidential against a compromised server.",
        ),
        ("TMS-2", "The cluster tolerates Byzantine replicas."),
        ("TMS-3", "These fixtures prove noninterference."),
        ("TMS-4", "A witness can undo the disclosure."),
    ];
    for (rule_id, sentence) in probes {
        let hits = scan_claims(sentence, &registry);
        assert!(
            hits.iter().any(|hit| hit.rule_id == rule_id),
            "rule {rule_id} did not fire on {sentence:?}: {hits:?}"
        );
    }
}

