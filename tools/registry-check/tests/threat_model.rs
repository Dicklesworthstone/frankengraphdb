//! Typed mutation and property suite for the G0 threat/trust model
//! (fgdb-g0-threat-model-nqd).
//!
//! Two kinds of test live here, and the distinction matters:
//!
//!   * **Registry mutation fixtures** take the frozen registry, break exactly
//!     one thing, and assert the checker reports the exact violation code. A
//!     checker nobody has watched go red is a checker nobody knows works.
//!   * **Attenuation property tests** run pseudo-random chains against the
//!     narrowing operators the REGISTRY declares, not against a hand-copied
//!     table. If the registry's operators drift, these fail — which is the
//!     point of deriving the lattice order from the registry.
//!
//! Determinism by default applies here too: the chain generator is a seeded
//! xorshift, so a failure is a seed, never a flake.

use registry_check::threat::{
    self, ThreatRegistry, expand_exposures, expand_footprint, expand_product_space, load_from_repo,
    scan_claims, validate_threat,
};
use std::path::{Path, PathBuf};

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("workspace root")
        .to_path_buf()
}

fn registry() -> ThreatRegistry {
    load_from_repo(&repo_root()).expect("threat_model.toml loads")
}

fn registry_text() -> String {
    std::fs::read_to_string(repo_root().join(threat::REGISTRY_PATH))
        .expect("read threat_model.toml")
}

/// Apply one textual mutation and return the violation codes it produces.
/// Panics if the mutation did not apply — a fixture that silently no-ops is a
/// fixture that passes for the wrong reason.
fn codes_after(original: &str, replacement: &str) -> Vec<String> {
    codes_after_all(&[(original, replacement)])
}

/// Apply several mutations in order. Needed when a single edit would produce a
/// DIFFERENT defect than the one under test — swapping two ordinals takes two
/// edits, and doing only half of it tests ordinal collision instead of order.
fn codes_after_all(edits: &[(&str, &str)]) -> Vec<String> {
    let mut text = registry_text();
    for (original, replacement) in edits {
        assert_eq!(
            text.matches(original).count(),
            1,
            "mutation anchor {original:?} must occur exactly once"
        );
        text = text.replacen(original, replacement, 1);
    }
    let mutated = text;
    let parsed = match threat::parse_threat(&mutated) {
        Ok(parsed) => parsed,
        // A mutation that makes the registry unparseable is also a rejection;
        // report it under a synthetic code so the fixture can assert on it.
        Err(error) => return vec![format!("load_error:{}", error.message)],
    };
    validate_threat(&parsed, &repo_root())
        .into_iter()
        .map(|violation| violation.code)
        .collect()
}

fn assert_code(codes: &[String], expected: &str) {
    assert!(
        codes.iter().any(|code| code == expected),
        "expected violation {expected:?}, got {codes:?}"
    );
}

