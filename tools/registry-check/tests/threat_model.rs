/// One dimension's value under the model. The variant is chosen by the
/// registry's declared narrowing operator, so the property suite cannot drift
/// from the frozen lattice order.
#[derive(Debug, Clone, PartialEq, Eq)]
enum DimValue {
    /// `fixed` — identical in every link.
    Fixed(u64),
    /// `intersect` — subsets only.
    Scope(Vec<u64>),
    /// `raise_only` — the bound may only move up.
    LowerBound(i64),
    /// `lower_only` — the bound may only move down.
    UpperBound(i64),
    /// `append_only` — entries may only be added.
    Appended(Vec<u64>),
    /// `restrict_disclosure_only` / `restrict_binding_only` — rank may only rise.
    Rank(u64),
    /// `current_state_monotone` — supplied by current state, monotone.
    Monotone(u64),
}

impl DimValue {
    fn seed(operator: &str, seed: u64) -> DimValue {
        match operator {
            "fixed" => DimValue::Fixed(seed),
            "intersect" => DimValue::Scope((0..8).map(|index| seed.wrapping_add(index)).collect()),
            "raise_only" => DimValue::LowerBound(0),
            "lower_only" => DimValue::UpperBound(1_000_000),
            "append_only" => DimValue::Appended(vec![seed]),
            "restrict_disclosure_only" | "restrict_binding_only" => DimValue::Rank(0),
            "current_state_monotone" => DimValue::Monotone(0),
            other => panic!("unmodelled narrowing operator {other:?}"),
        }
    }
}

/// Does `next` narrow `prior` under this operator? This is the whole lattice
/// order, in one function.
fn narrows(prior: &DimValue, next: &DimValue) -> bool {
    match (prior, next) {
        (DimValue::Fixed(a), DimValue::Fixed(b)) => a == b,
        (DimValue::Scope(a), DimValue::Scope(b)) => b.iter().all(|item| a.contains(item)),
        (DimValue::LowerBound(a), DimValue::LowerBound(b)) => b >= a,
        (DimValue::UpperBound(a), DimValue::UpperBound(b)) => b <= a,
        (DimValue::Appended(a), DimValue::Appended(b)) => {
            b.len() >= a.len() && b[..a.len()] == a[..]
        }
        (DimValue::Rank(a), DimValue::Rank(b)) => b >= a,
        (DimValue::Monotone(a), DimValue::Monotone(b)) => b >= a,
        _ => false,
    }
}

struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        // xorshift64*: deterministic, seeded, no dependency. A failing case is
        // a seed, not a flake.
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_f491_4f6c_dd1d)
    }

    fn below(&mut self, bound: usize) -> usize {
        if bound == 0 {
            0
        } else {
            (self.next() % bound as u64) as usize
        }
    }
}

/// Produce a legal narrowing successor for one dimension.
fn narrow_once(value: &DimValue, rng: &mut Rng) -> DimValue {
    match value {
        DimValue::Fixed(inner) => DimValue::Fixed(*inner),
        DimValue::Scope(items) => {
            if items.len() <= 1 {
                DimValue::Scope(items.clone())
            } else {
                let drop = rng.below(items.len());
                let mut next = items.clone();
                next.remove(drop);
                DimValue::Scope(next)
            }
        }
        DimValue::LowerBound(bound) => {
            DimValue::LowerBound(bound.saturating_add((rng.below(5)) as i64))
        }
        DimValue::UpperBound(bound) => {
            DimValue::UpperBound(bound.saturating_sub((rng.below(5)) as i64))
        }
        DimValue::Appended(items) => {
            let mut next = items.clone();
            next.push(rng.next());
            DimValue::Appended(next)
        }
        DimValue::Rank(rank) => DimValue::Rank((rank + rng.below(2) as u64).min(2)),
        DimValue::Monotone(value) => DimValue::Monotone(value + rng.below(3) as u64),
    }
}

/// Produce an ILLEGAL widening successor, or `None` when the value is already
/// at a bound where widening is not expressible.
fn widen_once(value: &DimValue) -> Option<DimValue> {
    match value {
        DimValue::Fixed(inner) => Some(DimValue::Fixed(inner.wrapping_add(1))),
        DimValue::Scope(items) => {
            let mut next = items.clone();
            next.push(u64::MAX);
            Some(DimValue::Scope(next))
        }
        DimValue::LowerBound(bound) => Some(DimValue::LowerBound(bound - 1)),
        DimValue::UpperBound(bound) => Some(DimValue::UpperBound(bound + 1)),
        DimValue::Appended(items) if !items.is_empty() => {
            Some(DimValue::Appended(items[..items.len() - 1].to_vec()))
        }
        DimValue::Appended(_) => None,
        DimValue::Rank(rank) if *rank > 0 => Some(DimValue::Rank(rank - 1)),
        DimValue::Rank(_) => None,
        DimValue::Monotone(value) if *value > 0 => Some(DimValue::Monotone(value - 1)),
        DimValue::Monotone(_) => None,
    }
}

/// tm_attenuation_narrowing_only — random chains over EVERY registered
/// dimension may only narrow, and every expressible widening mutation of every
/// dimension is rejected.
#[test]
fn tm_attenuation_narrowing_only() {
    let registry = registry();
    let operators: Vec<(String, String)> = registry
        .authority_dimensions
        .iter()
        .map(|dimension| (dimension.id.clone(), dimension.narrowing_operator.clone()))
        .collect();
    assert_eq!(
        operators.len(),
        27,
        "every §12.1/§12.2 dimension is modelled"
    );

    let mut widened_at_least_once = 0usize;
    for seed in 1u64..=256 {
        let mut rng = Rng(seed.wrapping_mul(0x9e37_79b9_7f4a_7c15) | 1);
        let mut chain: Vec<Vec<DimValue>> = vec![
            operators
                .iter()
                .map(|(_, operator)| DimValue::seed(operator, seed))
                .collect(),
        ];
        for _ in 0..6 {
            let prior = chain.last().expect("non-empty chain").clone();
            let next: Vec<DimValue> = prior
                .iter()
                .map(|value| narrow_once(value, &mut rng))
                .collect();
            chain.push(next);
        }
        // Every adjacent pair narrows, and narrowing is transitive along the
        // whole chain — a link cannot launder a widening through intermediates.
        for window in chain.windows(2) {
            for (index, (prior, next)) in window[0].iter().zip(&window[1]).enumerate() {
                assert!(
                    narrows(prior, next),
                    "seed {seed}: dimension {} widened: {prior:?} -> {next:?}",
                    operators[index].0
                );
            }
        }
        let first = chain.first().expect("non-empty");
        let last = chain.last().expect("non-empty");
        for (index, (prior, next)) in first.iter().zip(last).enumerate() {
            assert!(
                narrows(prior, next),
                "seed {seed}: dimension {} widened across the chain",
                operators[index].0
            );
        }
        // Every expressible widening mutation is rejected.
        for (index, value) in last.iter().enumerate() {
            if let Some(widened) = widen_once(value) {
                assert!(
                    !narrows(value, &widened),
                    "seed {seed}: widening dimension {} was accepted: {value:?} -> {widened:?}",
                    operators[index].0
                );
                widened_at_least_once += 1;
            }
        }
    }
    assert!(
        widened_at_least_once > 0,
        "the widening half of the property must not be vacuous"
    );
}

