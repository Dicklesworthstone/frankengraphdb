#[test]
fn tm_neg_binding_weakening() {
    // ATT-X5: Session/Channel binding never moves to a less restrictive class.
    let registry = registry();
    let rank = |name: &str| {
        registry
            .presentation_bindings
            .iter()
            .find(|binding| binding.name == name)
            .expect("binding registered")
            .rank
    };
    assert!(rank("ServerInternal") < rank("SessionBound"));
    assert!(rank("SessionBound") < rank("ChannelBound"));
    for transition in &registry.binding_transitions {
        let expected = rank(&transition.to) >= rank(&transition.from);
        assert_eq!(
            transition.legal, expected,
            "transition {}->{} legality contradicts the rank order",
            transition.from, transition.to
        );
    }
    let illegal: Vec<_> = registry
        .binding_transitions
        .iter()
        .filter(|transition| !transition.legal)
        .collect();
    assert_eq!(illegal.len(), 3, "exactly three weakening cells");
    for transition in illegal {
        assert_eq!(transition.law, "weakened_binding");
    }
    assert!(!narrows(&DimValue::Rank(2), &DimValue::Rank(1)));
}

