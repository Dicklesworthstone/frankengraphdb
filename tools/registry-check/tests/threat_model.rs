#[test]
fn tm_bound_claims_resolve_to_live_registry_rows() {
    let registry = registry();
    let invariants = std::fs::read_to_string(repo_root().join("registries/invariants.toml"))
        .expect("invariants");
    for id in &registry.registry.bound_invariants {
        assert!(
            invariants.contains(&format!("id = \"{id}\"")),
            "bound invariant {id} is not a live invariants.toml row"
        );
    }
    let evidence =
        std::fs::read_to_string(repo_root().join("registries/evidence.toml")).expect("evidence");
    for id in &registry.registry.bound_evidence {
        assert!(
            evidence.contains(&format!("id = \"{id}\"")),
            "bound evidence {id} is not a live evidence.toml row"
        );
    }
    // Every asset's primary claim must resolve too.
    for asset in &registry.assets {
        let found = invariants.contains(&format!("id = \"{}\"", asset.primary_claim_ref))
            || evidence.contains(&format!("id = \"{}\"", asset.primary_claim_ref));
        assert!(
            found,
            "asset {} names claim {} which resolves to no registry row",
            asset.id, asset.primary_claim_ref
        );
    }
}

