#[test]
fn topology_consume_rows_carry_resolvable_asset_evidence() {
    let registry = registry();
    let asupersync = block_text("plan-asupersync-assets-v1");
    let fnx = block_text("plan-fnx-assets-v1");
    for capability in registry
        .capabilities
        .iter()
        .filter(|row| row.disposition == "consume_from")
    {
        if registry
            .asset_evidence_gaps
            .iter()
            .any(|gap| gap.capability_id == capability.id)
        {
            continue;
        }
        let block = match capability.foundation_project.as_str() {
            "asupersync" => &asupersync,
            "franken_networkx" => &fnx,
            other => panic!("unexpected foundation project {other:?}"),
        };
        let hits = block
            .lines()
            .filter(|line| line.contains(&capability.foundation_asset))
            .count();
        assert_eq!(hits, 1, "{} asset evidence must be exact", capability.id);
    }
}

