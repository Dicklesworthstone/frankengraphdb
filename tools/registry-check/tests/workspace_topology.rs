#[test]
fn topology_crate_universe_is_derived_from_the_frozen_table() {
    let registry = registry();
    let parsed = parse_layer_table(&block_text("plan-crate-layer-table-v1")).expect("table parses");
    assert_eq!(parsed.len(), registry.layers.len());
    let declared: BTreeSet<&str> = registry
        .crates
        .iter()
        .map(|row| row.name.as_str())
        .collect();
    let spelled: BTreeSet<&str> = parsed
        .iter()
        .flat_map(|row| row.tokens.iter().map(String::as_str))
        .collect();
    assert!(
        spelled.difference(&declared).next().is_none(),
        "the plan spells crates the registry does not declare: {:?}",
        spelled.difference(&declared).collect::<Vec<_>>()
    );
    assert_eq!(
        spelled.len(),
        declared.len(),
        "every declared crate must be spelled by the frozen table"
    );
}

#[test]
fn topology_layer_table_parser_keeps_source_order_and_drops_cross_references() {
    let parsed = parse_layer_table(&block_text("plan-crate-layer-table-v1")).expect("parses");
    let loom = parsed
        .iter()
        .find(|row| row.title == "Loom")
        .expect("Loom row");
    // The Loom row's annotation cross-references a Txn crate. The parser keeps
    // the token (coverage) and the membership law filters it by layer — which is
    // the whole reason membership is checked per-layer rather than per-token.
    assert!(loom.tokens.contains(&"fgdb-secure-view".to_string()));
    assert_eq!(
        loom.tokens.first().map(String::as_str),
        Some("fgdb-gql"),
        "source order, not alphabetical: the census sorts, the source spells"
    );
    let aegis = parsed
        .iter()
        .find(|row| row.title == "Aegis")
        .expect("Aegis row");
    assert!(aegis.tokens.contains(&"fgdb-order".to_string()));
    assert!(aegis.tokens.contains(&"fgdb-shard".to_string()));
}

