//! Typed mutation, derivation, and property suite for the frozen workspace
//! topology (fgdb-g0-workspace-topology-1q9m).
//!
//! Four kinds of test live here, and the distinction matters:
//!
//!   * **Derivation tests** prove the crate universe, the inventory partition,
//!     and the donor bijection are computed FROM the frozen plan blocks rather
//!     than retyped next to them.
//!   * **Registry mutation fixtures** take the frozen registry, break exactly
//!     one thing, and assert the checker reports the exact violation code. A
//!     checker nobody has watched go red is a checker nobody knows works.
//!   * **Synthetic-graph property tests** exercise the laws that CANNOT fire
//!     against today's tree, because the crates they govern do not exist yet:
//!     posture closures, crate-graph cycles, layer inversion. Without these the
//!     green bar would be reporting "no composition crate is active", which
//!     reads exactly like "no composition crate is misplaced".
//!   * **Scanner tests** pin the manifest reader's subset and its fail-closed
//!     behaviour, because a scanner that silently skips what it does not
//!     understand turns every closed-universe law into a suggestion.
//!
//! The hash pins are duplicated here on purpose. `topology-check` recomputes
//! them from the registry it just read, so a coordinated edit of rows AND
//! header keeps the binary green; a constant in a test file does not move
//! unless someone moves it.

use registry_check::topology::{
    self, AssetEvidenceGap, Capability, ManifestDependency, ScannedCrate, TopologyRegistry,
    WorkspaceScan, crate_graph_cycle, decompose_inventory, design_bijection, load_from_repo,
    parse_layer_table, posture_closures, recompute_id_table_hash, recompute_semantic_contract_hash,
    required_edge_coverage, required_edge_floor_violations, scan_manifest, scan_workspace,
    source_block_text, validate_topology,
};
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

const ID_TABLE_PIN: &str = "fnv1a64:b422bc59c3da23ca";
// Re-frozen on each crate activation (fgdb-reference 08bfadf, fgdb-sim,
// fgdb-strata, then fgdb by fgdb-j0vu). Derived from the gate's own drift
// message, never hand-computed. The semantic contract covers activation_status
// AND posture status, so activating a crate MUST move this — a pin that
// survived the change would be pinning nothing.
const SEMANTIC_CONTRACT_PIN: &str = "fnv1a64:b87cb355fab8bcd8";

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("workspace root")
        .to_path_buf()
}

fn registry() -> TopologyRegistry {
    load_from_repo(&repo_root()).expect("workspace_topology.toml loads")
}

fn registry_text() -> String {
    std::fs::read_to_string(repo_root().join(topology::REGISTRY_PATH))
        .expect("read workspace_topology.toml")
}

fn block_text(id: &str) -> String {
    let registry = registry();
    let block = registry.source_block(id).expect("source block exists");
    source_block_text(block, &repo_root()).expect("block reads")
}

/// Apply one textual mutation and return the violation codes it produces.
/// Panics if the mutation did not apply — a fixture that silently no-ops is a
/// fixture that passes for the wrong reason.
fn codes_after(original: &str, replacement: &str) -> Vec<String> {
    codes_after_all(&[(original, replacement)])
}

fn codes_after_all(edits: &[(&str, &str)]) -> Vec<String> {
    let mut text = registry_text();
    for (original, replacement) in edits {
        assert_eq!(
            text.matches(original).count(),
            1,
            "mutation anchor {original:?} must occur exactly once"
        );
        text = text.replacen(original, replacement, 1);
    }
    let mutated = topology::parse_topology(&text).expect("mutated registry still parses");
    let mut codes: Vec<String> = validate_topology(&mutated, &repo_root())
        .into_iter()
        .map(|violation| violation.code)
        .collect();
    codes.sort();
    codes.dedup();
    codes
}

fn assert_reports(codes: &[String], expected: &str) {
    assert!(
        codes.iter().any(|code| code == expected),
        "expected violation {expected:?}, got {codes:?}"
    );
}

