fn synthetic_crate(name: &str, deps: &[&str]) -> ScannedCrate {
    ScannedCrate {
        dir: format!("crates/{name}"),
        package_name: name.to_string(),
        dependencies: deps
            .iter()
            .map(|dep| ManifestDependency {
                key: (*dep).to_string(),
                package: (*dep).to_string(),
                table: "dependencies".to_string(),
                path: format!("../{dep}"),
                git: String::new(),
                rev: String::new(),
                default_features_disabled: false,
            })
            .collect(),
        lints_workspace: true,
        root_path: "src/lib.rs".to_string(),
        root_forbids_unsafe: true,
        root_denies_unsafe: false,
        relaxes_unsafe: false,
    }
}

fn synthetic_scan(crates: Vec<ScannedCrate>) -> WorkspaceScan {
    WorkspaceScan {
        members: crates.iter().map(|entry| entry.dir.clone()).collect(),
        workspace_unsafe_lint: "forbid".to_string(),
        toolchain_channel: "nightly-2026-07-05".to_string(),
        crates,
    }
}

